// Generate RESULTS.md from results/summary.json. RESULTS.md is therefore always
// derived from a real run — never hand-edited. Run: node report.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SUMMARY = path.join(__dirname, "results", "summary.json");
const OUT = path.join(__dirname, "RESULTS.md");

if (!fs.existsSync(SUMMARY)) {
  console.error("No results/summary.json — run `node bench.mjs` first.");
  process.exit(1);
}
const s = JSON.parse(fs.readFileSync(SUMMARY, "utf8"));
const L = [];
const p = (x = "") => L.push(x);

const num = (x) => (x == null ? "—" : String(x));
// Load p99 cell, annotated with timeouts/errors so a capped tail isn't misread.
function loadP99(l) {
  if (!l || l.error) return l?.error ? "err" : "—";
  const p99 = l.latencyMs?.p99;
  const flags = [];
  if (l.timeouts) flags.push(`${l.timeouts} to`);
  if (l.non2xx) flags.push(`${l.non2xx} non2xx`);
  if (l.errors && l.errors !== l.timeouts) flags.push(`${l.errors} err`);
  return `${num(p99)}${flags.length ? ` ⚠(${flags.join(", ")})` : ""}`;
}
const bytes = (x) => (x == null ? "—" : x >= 1024 ? `${(x / 1024).toFixed(1)} KiB` : `${x} B`);

p("# Benchmark Results");
p("");
p("> Generated by `node report.mjs` from `results/summary.json`. Do not hand-edit.");
p("> **No winner is declared.** Numbers are only comparable within the caveats in the last section.");
p("> 📊 Visual charts: see [`CHARTS.md`](CHARTS.md).");
p("");

// Environment block
const e = s.environment;
p("## Environment");
p("");
p("| | |");
p("|---|---|");
p(`| Captured | ${e.capturedAt} |`);
p(`| CPU | ${e.cpu.model} |`);
p(`| Logical cores | ${e.cpu.logicalCores} |`);
p(`| RAM | ${e.memoryGiB} GiB |`);
p(`| OS | ${e.os.version} (${e.os.arch}) |`);
p(`| Node | ${e.runtimes.node} |`);
p(`| pnpm | ${e.runtimes.pnpm ?? "—"} |`);
p(`| Go | ${e.runtimes.go ?? "—"} |`);
p("");
p(`Measurement config: **${s.config.runs} runs** per scenario, first **${s.config.warmupDiscarded}** discarded as warmup; load = **${s.config.loadDurationSec}s** at **${s.config.connections}** connections. Production builds only, one entry at a time.`);
p("");

// Per-entry build/start/memory
p("## Build, cold start, and memory");
p("");
p("| Entry | Kind | Outcome | Cold build (ms) | Warm build (ms) | Cold start (ms) | RSS idle (MiB) | RSS under load (MiB) |");
p("|---|---|---|---|---|---|---|---|");
for (const en of s.entries) {
  p(
    `| ${en.name} | ${en.kind} | ${en.outcome} | ${num(en.build?.cold?.ms)} | ${num(en.build?.warm?.ms)} | ${num(en.server?.coldStartMs)} | ${num(en.memoryMiB?.idle)} | ${num(en.memoryMiB?.underLoadMax)} |`,
  );
}
p("");

// Client JS bytes
p("## Client JS bytes (framework runtime vs app code)");
p("");
p("| Entry | Total raw | Total gzip | Total brotli | Framework raw | App raw | Split source |");
p("|---|---|---|---|---|---|---|");
for (const en of s.entries) {
  const cj = en.clientJsBytes ?? {};
  // Total = sum of all real bundle groups (exclude the attribution object).
  let raw = 0, gzip = 0, brotli = 0, hasGroup = false;
  for (const [k, v] of Object.entries(cj)) {
    if (k === "attributionRawBytes" || !v || typeof v.raw !== "number") continue;
    hasGroup = true;
    raw += v.raw; gzip += v.gzip; brotli += v.brotli;
  }
  let fwRaw, appRaw, splitSrc;
  if (cj.attributionRawBytes) {
    fwRaw = cj.attributionRawBytes.frameworkRawBytes;
    appRaw = cj.attributionRawBytes.appRawBytes;
    splitSrc = "metafile (exact)";
  } else if (cj.framework || cj.app) {
    fwRaw = cj.framework?.raw;
    appRaw = cj.app?.raw;
    splitSrc = "filename (heuristic)";
  } else {
    splitSrc = "—";
  }
  p(
    `| ${en.name} | ${hasGroup ? bytes(raw) : "—"} | ${hasGroup ? bytes(gzip) : "—"} | ${hasGroup ? bytes(brotli) : "—"} | ${bytes(fwRaw)} | ${bytes(appRaw)} | ${splitSrc} |`,
  );
}
p("");

// Per-scenario timing tables
const scenarioTitles = {
  1: "Static page, no data",
  2: "Server component awaiting 50ms source, Suspense-streamed",
  3: "Interactive client island in a server tree",
  4: "Nested Suspense, 3 boundaries @ 20/50/200ms (RSC-only)",
};
for (const id of ["1", "2", "3", "4"]) {
  p(`## Scenario ${id} — ${scenarioTitles[id]}`);
  p("");
  p("TTFB and TTLB are milliseconds (median / p95 / p99, CoV%). For RSC entries the two-request model is measured separately: **document** (the shell) and **RSC Flight** (the payload).");
  p("");
  p("| Entry | Request | TTFB med | TTFB p95 | TTLB med | TTLB p95 | TTLB p99 | CoV% | Payload raw | gzip | brotli | Load req/s | Load p99 ms |");
  p("|---|---|---|---|---|---|---|---|---|---|---|---|---|");
  for (const en of s.entries) {
    const sc = en.scenarios?.find((x) => x.scenario === id);
    if (!sc) continue;
    if (sc.outcome !== "ok") {
      p(`| ${en.name} | — | \`${sc.outcome}\`${sc.reason ? " — " + sc.reason.slice(0, 60) : ""} | | | | | | | | | | |`);
      continue;
    }
    // document row
    const dt = sc.timings.documentTtfbMs, dl = sc.timings.documentTtlbMs;
    const dp = sc.payloadBytes.document, dloadObj = sc.load.document;
    p(
      `| ${en.name} | document | ${num(dt.median)} | ${num(dt.p95)} | ${num(dl.median)} | ${num(dl.p95)} | ${num(dl.p99)} | ${num(dl.cvPct)} | ${bytes(dp.raw)} | ${bytes(dp.gzip)} | ${bytes(dp.brotli)} | ${num(dloadObj?.requests?.perSec)} | ${loadP99(dloadObj)} |`,
    );
    if (sc.twoRequest && sc.timings.flightTtfbMs) {
      const ft = sc.timings.flightTtfbMs, fl = sc.timings.flightTtlbMs;
      const fp = sc.payloadBytes.rscFlight, floadObj = sc.load.rscFlight;
      p(
        `| ${en.name} | RSC Flight | ${num(ft.median)} | ${num(ft.p95)} | ${num(fl.median)} | ${num(fl.p95)} | ${num(fl.p99)} | ${num(fl.cvPct)} | ${bytes(fp?.raw)} | ${bytes(fp?.gzip)} | ${bytes(fp?.brotli)} | ${num(floadObj?.requests?.perSec)} | ${loadP99(floadObj)} |`,
      );
    }
  }
  p("");
  // flush timelines
  p(`### Scenario ${id} flush timelines (representative run)`);
  p("");
  for (const en of s.entries) {
    const sc = en.scenarios?.find((x) => x.scenario === id);
    if (!sc || sc.outcome !== "ok") continue;
    const doc = sc.flushTimeline?.document ?? [];
    p(`- **${en.name}** document (${doc.length} chunk${doc.length === 1 ? "" : "s"}): ${doc.map((c) => `${c.tMs}ms/${c.bytes}B`).join(" → ") || "—"}`);
    if (sc.twoRequest && sc.flushTimeline?.rscFlight) {
      const fl = sc.flushTimeline.rscFlight;
      p(`- **${en.name}** RSC Flight (${fl.length} chunk${fl.length === 1 ? "" : "s"}): ${fl.map((c) => `${c.tMs}ms/${c.bytes}B`).join(" → ") || "—"}`);
    }
  }
  p("");
}

// Conformance
p("## Conformance gate");
p("");
p("Normalized rendered DOM must match across implementations of a scenario (scripts, comments, and framework-specific attributes stripped). SSR entries are compared from first-response HTML; RSC entries whose first response is a shell require browser-rendered capture (marked pending).");
p("");
p("| Scenario | Verdict | Compared (SSR) | Pending browser capture |");
p("|---|---|---|---|");
for (const [id, c] of Object.entries(s.conformance)) {
  const verdict = c.comparedEntries.length <= 1 ? "n/a (need ≥2)" : c.conformant ? "PASS" : "FAIL";
  p(`| ${id} | ${verdict} | ${c.comparedEntries.join(", ") || "—"} | ${c.pendingBrowserCapture.join(", ") || "—"} |`);
}
p("");

// Notes / caveats
p("## Caveats (where this isn't apples-to-apples)");
p("");
p("See `FAIRNESS.md` for the full deviation log. Per-entry notes captured this run:");
p("");
for (const en of s.entries) {
  if (!en.notes?.length) continue;
  p(`**${en.name}:**`);
  for (const n of en.notes) p(`- ${n}`);
  p("");
}
p("Harness-level caveats:");
p("- Build peak-RSS is unreliable for sub-second builds and for bundlers that run as a child service process (e.g. esbuild) — the single-pid `ps` sampler under-counts. Treat build memory as indicative only.");
p("- RSS is sampled on the server's main pid; multi-process servers would under-count (recorded per entry where relevant).");
p("- TTFB/TTLB are measured from a local loopback client (no network latency); they reflect server+render cost, not real-world RTT.");
p("");

fs.writeFileSync(OUT, L.join("\n"));
console.log(`Wrote ${path.relative(__dirname, OUT)} (${s.entries.length} entries).`);
